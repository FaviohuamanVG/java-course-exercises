package Understanding_Java_Arrays.Varargs;

public class Methods {
    /*  
    Argumentos Variables (Varargs):
    Los varargs permiten que un método reciba un número variable de 
    argumentos del mismo tipo usando tres puntos seguidos (...).
    */
   public static void main(String[] args) {
    // public static void main(String[] args)
    // public static void main(String args[])
    // public static void main(String... args) // Sintaxis de varargs
    // Dentro del cuerpo del método, la variable definida con varargs 
    // se maneja exactamente igual que un arreglo normal.
    // Puedes acceder a sus miembros usando la sintaxis habitual de un arreglo, 
    // por ejemplo: args.length y args[0].

    System.out.println("Argumentos Variables (Varargs)");
   }
}
