package Creating_and_Manipulating_Strings.The_important_String_Methods.length;

public class Length {
    /*  
    Un string tiene una secuencia de caracteres y Java cuenta las
    posiciones(Indices) desde 0 no desde 1
    */

    // Metodo length:
    public static void main(String[] args) {
        String name = "Animals"; // El output nos dara 6 siguiente la regla de los indices, no?
        System.out.println(name.length()); // Resultado es 7
        /*
        Indices y posiciones es desde 0, la ultima letra del indice es 6
        Pero la longitud y el tamaño total es 7 osea el conteo es normal
        */

    }

    
}
